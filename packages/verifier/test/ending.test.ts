// conformance v3: the ending, the draw and the lock vesting. The vectors are computed by a Python generator from the specification and the program
// source (not by running Rust: see `source` in the file); this runs the verifier's own implementation and the helpers of the client package against them.
import { describe, expect, it } from 'vitest';
import { placementAt, lastBucket as clientLastBucket, auxShardIndexesFor, auxBit } from '@opening-cross/cross-core-client';
import { type Implementation3, loadVectors3, referenceImplementation3, runConformance3 } from '../src/index.js';

describe('conformance v3', () => {
  const vectors = loadVectors3();

  it('says where its expected values came from, and that it did not run the Rust code', () => {
    expect(vectors.source).toMatch(/NOT generated by running the Rust code/);
    expect(vectors.generator).toMatch(/generate_v3\.py/);
  });

  it('covers every function it claims to', () => {
    const kinds = new Set(vectors.cases.map((c) => c.kind));
    expect([...kinds].sort()).toEqual(['draw_end_bucket', 'draw_extension_secs', 'draw_lottery_start', 'excluded', 'lock', 'placement', 'required_aux']);
    expect(vectors.cases.length).toBeGreaterThan(500);
    // the assertions of the Rust unit test of CrossExt::placement are in it
    expect(vectors.cases.filter((c) => c.kind === 'placement' && c.tag === 'rust-unit-test').length).toBe(8);
  });

  it('the verifier\'s implementation reproduces every case', () => {
    expect(runConformance3(vectors, referenceImplementation3)).toEqual([]);
  });

  it('a single wrong answer is reported', () => {
    const off: Implementation3 = (c) => {
      const r = referenceImplementation3(c);
      return c.kind === 'draw_end_bucket' && c.buckets === 8 && c.seed === (vectors.cases.find((x) => x.kind === 'draw_end_bucket')! as { seed: string }).seed ? ((r as number) + 1) % 8 : r;
    };
    expect(runConformance3(vectors, off).length).toBeGreaterThan(0);
  });

  it('the client package\'s helpers agree with the same vectors (placement, last bucket, auxiliary shard bits)', () => {
    for (const c of vectors.cases) {
      if (c.kind === 'placement') {
        const ext = { draw: { epoch: c.epoch }, ending: { endingSecs: c.endingSecs, buckets: c.buckets } } as never;
        expect(placementAt(ext, BigInt(c.closeTs), BigInt(c.now))).toEqual(c.expect);
      }
      if (c.kind === 'required_aux') {
        // the client names the shard indexes; the mask is the bits of the buckets up to the last counted one and of the extension shards after an extension
        const last = clientLastBucket({ draw: { endBucket: c.endBucket }, ending: { buckets: c.buckets } } as never);
        let mask = 0n;
        if (c.endingSecs > 0) for (const i of auxShardIndexesFor({ endingSecs: c.endingSecs, buckets: c.buckets, extensionMaxSecs: 0 }, c.shards)) if (i - 32 <= last) mask |= auxBit(i);
        if (c.epoch > 0) for (const i of auxShardIndexesFor({ endingSecs: 0, buckets: 0, extensionMaxSecs: 1 }, c.shards)) mask |= auxBit(i);
        expect(mask.toString(), JSON.stringify(c)).toBe(c.expect);
      }
    }
  });
});
